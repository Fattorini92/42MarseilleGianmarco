#include "libft.h"

void ft_putnbr_fd(int n, int fd)
{
	int nb;
	nb = n;
	if (nb == -2147483648)
	{
		write(fd, "-2147483648", 11);
		return;
	}
	if (nb < 0)
	{
		ft_putchar_fd('-', fd);
		nb = -nb;
	}
	if (nb > 9)
	{
		ft_putnbr_fd(nb / 10, fd);
		ft_putchar_fd(nb % 10 + '0', fd);
	}
	else
		ft_putchar_fd(nb + '0', fd);
}
